import Testing
import Foundation
import CoreGraphics
@testable import ClipboardFeature

@Suite struct PasteboardSnapshotTests {
    func snap(_ c: [String: Data]) -> CapturedClip? {
        let pb = FakePasteboard(); pb.set(c)
        return PasteboardSnapshot.capture(from: pb, sourceBundleID: "com.apple.Notes")
    }
    @Test func textWithFormatting() throws {
        let c = try #require(snap([plainType: Data("merhaba".utf8), "public.rtf": Data("{\\rtf1 merhaba}".utf8), "com.microsoft.excel.xls": Data([9])]))
        #expect(c.kind == .text); #expect(c.plainText == "merhaba")
        #expect(Set(c.representations.map(\.type)) == [plainType, "public.rtf"])
        #expect(c.dedupKey == "t:" + Hashing.sha256Hex(Data("merhaba".utf8)))
        #expect(c.sourceBundleID == "com.apple.Notes")
    }
    @Test func skipsTransientAutoGeneratedAndFinderFiles() {
        #expect(snap([plainType: Data("x".utf8), "org.nspasteboard.TransientType": Data()]) == nil)
        #expect(snap([plainType: Data("x".utf8), "org.nspasteboard.AutoGeneratedType": Data()]) == nil)
        #expect(snap([plainType: Data("dosya.pdf".utf8), "public.file-url": Data("file:///a".utf8), "public.tiff": makePNG(width: 4, height: 4)]) == nil)
    }
    @Test func concealedCapturedAsNormalText() throws {
        let c = try #require(snap([plainType: Data("parola123".utf8), "org.nspasteboard.ConcealedType": Data()]))
        #expect(c.plainText == "parola123"); #expect(c.representations.map(\.type) == [plainType])
    }
    @Test func imageAndHtmlWithoutPlainTextIsImage() throws {
        let c = try #require(snap(["public.png": makePNG(width: 40, height: 30), "public.html": Data("<img>".utf8)]))
        #expect(c.kind == .image); #expect(c.imagePixelSize == CGSize(width: 40, height: 30))
        #expect(c.dedupKey.hasPrefix("i:")); #expect(c.plainText == nil)
    }
    @Test func rejectsEmptyWhitespaceAndOversize() {
        #expect(snap([:]) == nil)
        #expect(snap([plainType: Data("  \n ".utf8)]) == nil)
        #expect(snap([plainType: Data(repeating: 0x61, count: PasteboardSnapshot.maxTotalBytes + 1)]) == nil)
    }
    @Test func thumbnailFitsMaxPixel() throws {
        let t = try #require(ImageThumbnail.pngThumbnail(from: makePNG(width: 400, height: 200), maxPixel: 96))
        #expect(ImageThumbnail.pixelSize(of: t) == CGSize(width: 96, height: 48))
    }
}
